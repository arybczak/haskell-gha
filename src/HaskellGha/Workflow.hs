{-# LANGUAGE OverloadedStrings #-}

-- | The generated workflow.
module HaskellGha.Workflow
  ( -- * Workflow
    generate
  , workflow
  , renderWorkflow
  ) where

import Control.Monad
import Data.Char
import Data.Foldable
import Data.Functor
import Data.List qualified as L
import Data.Text qualified as T
import Distribution.Pretty
import Distribution.Version
import System.FilePath

import HaskellGha.Check
import HaskellGha.Config
import HaskellGha.Ghc
import HaskellGha.Options
import HaskellGha.Project
import HaskellGha.Yaml

-- | Read the configuration and the project, and make the workflow. The phases
-- run in order, and each phase shows all its errors.
generate :: Options -> IO (Either [String] Node)
generate opts =
  readConfig opts.config >>= \case
    Left errors -> pure $ Left errors
    Right config ->
      readProject opts.projectDir >>= \case
        Left errors -> pure $ Left errors
        Right project -> pure $ workflow opts config project

-- | Render the workflow with its header comment.
renderWorkflow
  :: String
  -- ^ The version of the tool.
  -> Options
  -> Node
  -> T.Text
renderWorkflow version opts =
  renderYaml
    [ "This file was generated by haskell-gha, do not edit it."
    , ""
    , "To regenerate it, run:"
    , "  " <> T.unwords (map (shellQuote . T.pack) $ commandLine opts)
    , ""
    , "Version: " <> T.pack version
    , ""
    , "For more information, see https://github.com/arybczak/haskell-gha"
    ]

-- | Quote a word for bash, if it needs quotes.
shellQuote :: T.Text -> T.Text
shellQuote t
  | not (T.null t) && T.all (\c -> isAsciiLower c || isAsciiUpper c || isDigit c || c `elem` ("-_./=:+@%," :: String)) t = t
  | otherwise = "'" <> T.replace "'" "'\\''" t <> "'"

-- | Make the workflow.
workflow :: Options -> Config -> Project -> Either [String] Node
workflow opts config project = runCheck $ checks $> root
  where
    entries :: [GhcEntry]
    entries = map (.ghc) project.matrix

    checks :: Check ()
    checks =
      traverse_ checkGhcValue (matrixGhcValues config)
        *> for_ config.doctest (\d -> traverse_ (checkDoctestRange d) entries *> traverse_ checkSkip d.skip)
        *> when config.sdist (traverse_ checkImport project.imports *> traverse_ checkInside project.packages)
        *> for_ config.hlint (traverse_ checkHLintPath . (.path))

    -- The action gets the path on the runner, where only the repository
    -- exists.
    checkHLintPath :: T.Text -> Check ()
    checkHLintPath p
      | isAbsolute (T.unpack p) || leadsAbove (projectDir </> T.unpack p) =
          failure $
            "The field hlint.path contains the path "
              ++ T.unpack p
              ++ ", which is not in the repository. Give a path relative to the project directory."
      | otherwise = pure ()

    -- cabal fetches an import from a URL, so only a local file is missing from
    -- the copy.
    checkImport :: Import -> Check ()
    checkImport i
      | "://" `L.isInfixOf` i.target = pure ()
      | otherwise =
          failure $
            i.location
              ++ "the workflow builds the source tarballs in a copy of the project directory, and the copy does not contain the imported file "
              ++ i.target
              ++ ". Set sdist: false in the configuration."

    -- The unpack step keeps the path of each package relative to the project
    -- directory, so a path with .. leads out of the copy.
    checkInside :: Package -> Check ()
    checkInside p
      | leadsAbove p.directory =
          failure $
            "Package "
              ++ p.name
              ++ " is in "
              ++ p.directory
              ++ ", outside the project directory, but the workflow builds the source tarballs in a copy of the project directory. Set sdist: false in the configuration."
      | otherwise = pure ()

    checkDoctestRange :: Doctest -> GhcEntry -> Check ()
    checkDoctestRange d = fromEither . void . decideRange ("The range " ++ prettyShow d.ghc ++ " of the field doctest.ghc") d.ghc

    checkSkip :: T.Text -> Check ()
    checkSkip p
      | T.unpack p `elem` map (.name) project.packages = pure ()
      | otherwise = failure $ "The field doctest.skip names the package " ++ T.unpack p ++ ", but the project has no such local package."

    checkGhcValue :: T.Text -> Check ()
    checkGhcValue value
      | value `elem` map entryText entries = pure ()
      | otherwise =
          failure $
            "The matrix of the configuration refers to GHC "
              ++ T.unpack value
              ++ ", but the ghc axis contains only "
              ++ L.intercalate ", " (map (T.unpack . entryText) entries)
              ++ "."

    root :: Node
    root =
      Mapping
        ( topLevel
            [ ("name", config.name)
            , ("on", triggers)
            , ("permissions", config.permissions)
            , -- A push to a branch of the push trigger also cancels the older
              -- run. The newer run tests the newer code and saves the cache
              -- that the older run did not save.
              ("concurrency", mapping [("group", plain "${{ github.workflow }}-${{ github.ref }}"), ("cancel-in-progress", plain "true")])
            , ("defaults", mapping [("run", mapping $ ("shell", plain "bash") : workingDirectory)])
            ,
              ( "jobs"
              , Mapping $
                  item (Key Plain "build", job)
                    : [Item True (Key Plain "fourmolu", fourmoluJob f) | Just f <- [config.fourmolu]]
                    ++ [Item True (Key Plain "hlint", hlintJob h) | Just h <- [config.hlint]]
              )
            ]
        )

    topLevel :: [(T.Text, Node)] -> [Item (Key, Node)]
    topLevel = zipWith (\i (k, v) -> Item (i > (0 :: Int)) (Key Plain k, v)) [0 ..]

    triggers :: Node
    triggers =
      mapping
        [ ("push", mapping [("branches", sequenceOf config.branches)])
        , ("pull_request", plain "")
        , ("merge_group", plain "")
        , ("workflow_dispatch", plain "")
        ]

    workingDirectory :: [(T.Text, Node)]
    workingDirectory = [("working-directory", plain (T.pack projectDir)) | projectDir /= "."]

    projectDir :: FilePath
    projectDir = dropTrailingPathSeparator (normalise opts.projectDir)

    job :: Node
    job =
      Mapping
        ( map item $
            [ (Key Plain "name", jobName)
            , (Key Plain "runs-on", config.runsOn)
            ]
              ++ [(Key Plain "services", s) | Just s <- [config.services]]
              ++ [ (Key Plain "strategy", mapping [("fail-fast", plain "false"), ("matrix", matrix)])
                 , (Key Plain "steps", Sequence (separate steps))
                 ]
        )

    -- The job needs no GHC, so it runs once, next to the build jobs.
    fourmoluJob :: Fourmolu -> Node
    fourmoluJob f =
      mapping
        [ ("name", plain "Fourmolu")
        , ("runs-on", config.runsOn)
        ,
          ( "steps"
          , Sequence
              ( separate
                  [ item checkoutStep
                  , item $
                      mapping
                        [ ("uses", plain ("haskell-actions/run-fourmolu@" <> config.actions.runFourmolu))
                        ,
                          ( "with"
                          , mapping $
                              [("version", singleQuoted (T.pack (prettyShow f.version)))]
                                ++ [("pattern", literal (T.unlines f.patterns)) | not (null f.patterns)]
                                -- The run defaults do not apply to an action.
                                ++ [("working-directory", plain (T.pack projectDir)) | projectDir /= "."]
                          )
                        ]
                  ]
              )
          )
        ]

    hlintJob :: HLint -> Node
    hlintJob h =
      mapping
        [ ("name", plain "HLint")
        , ("runs-on", config.runsOn)
        ,
          ( "steps"
          , Sequence
              ( separate
                  [ item checkoutStep
                  , item $
                      mapping
                        [ ("uses", plain ("haskell-actions/hlint-setup@" <> config.actions.hlintSetup))
                        , ("with", mapping [("version", singleQuoted (T.pack (prettyShow h.version)))])
                        ]
                  , item $
                      mapping
                        [ ("uses", plain ("haskell-actions/hlint-run@" <> config.actions.hlintRun))
                        , ("with", mapping $ [("path", p) | Just p <- [hlintPath h]] ++ [("fail-on", plain h.failOn)])
                        ]
                  ]
              )
          )
        ]

    -- The action runs in the root of the repository and takes one path, or a
    -- JSON array of paths. Without a path, it checks the root.
    hlintPath :: HLint -> Maybe Node
    hlintPath h = case paths of
      ["."] -> Nothing
      [p] -> Just (singleQuoted (T.pack p))
      ps -> Just (singleQuoted ("[" <> T.intercalate ", " (map (jsonString . T.pack) ps) <> "]"))
      where
        paths :: [FilePath]
        paths
          | null h.path = [projectDir]
          | otherwise = [dropTrailingPathSeparator (normalise (projectDir </> T.unpack p)) | p <- h.path]

        jsonString :: T.Text -> T.Text
        jsonString t = "\"" <> T.concatMap (\c -> if c `elem` ['"', '\\'] then T.pack ['\\', c] else T.singleton c) t <> "\""

    checkoutStep :: Node
    checkoutStep = mapping [("uses", plain ("actions/checkout@" <> config.actions.checkout))]

    jobName :: Node
    jobName = case matrixAxes config of
      [] -> plain "GHC ${{ matrix.ghc }}"
      axes -> singleQuoted . T.intercalate ", " $ "GHC ${{ matrix.ghc }}" : [a <> " ${{ matrix." <> a <> " }}" | a <- axes]

    matrix :: Node
    matrix =
      Mapping (item (Key Plain "ghc", sequenceOf (map (singleQuoted . entryText) entries)) : config.matrix)

    -- An empty line before each step except the first.
    separate :: [Item Node] -> [Item Node]
    separate = zipWith (\i s -> s {emptyLine = i > (0 :: Int)}) [0 ..]

    steps :: [Item Node]
    steps =
      concat
        [ [item checkoutStep]
        , [item $ runStep "Install the system packages" Nothing (aptScript config.apt) | not (null config.apt)]
        , [item setupStep]
        , [item versionsStep]
        , [ item $ runStep "Unpack the source tarballs" (Just group) (unpackScript pkgs)
          | config.sdist
          , (group, pkgs) <- packageGroups project.matrix
          ]
        , [item $ sourceStep "Configure the project" Nothing configureScript]
        , [ item $ sourceStep "Enable parallel module builds for the local packages" (Just group) (parallelScript pkgs)
          | (group, pkgs) <- packageGroups [e | e <- project.matrix, not (hasSemaphore e.ghc)]
          ]
        , [ item $ sourceStep "Enable the GHC job semaphore" (Just semaphoreEntries) "echo 'semaphore: True' >> cabal.project.local\n"
          | not (null semaphoreEntries)
          ]
        , [item planStep]
        , [item cacheRestore]
        , [item $ sourceStep "Build the dependencies" Nothing "cabal build all --only-dependencies\n"]
        , [item cacheSave]
        , concat
            [ doctestSteps d
            | not (null doctestEntries)
            , Just d <- [config.doctest]
            ]
        , config.hooks.beforeBuild
        , [item $ sourceStep "Build" Nothing "cabal build all\n"]
        , config.hooks.afterBuild
        , [ item $ sourceStep "Run the tests" (Just testEntries) "cabal test all --test-show-details=direct\n"
          | config.tests
          , not (null testEntries)
          ]
        , [ item $ sourceStep ("Run doctest for " <> T.pack p.name) (Just es) (doctestScript d p)
          | Just d <- [config.doctest]
          , p <- project.packages
          , T.pack p.name `notElem` d.skip
          , not (null p.doctestArgs)
          , let es = [e.ghc | e <- project.matrix, e.ghc `elem` doctestEntries, p.directory `elem` map (.directory) e.packages]
          , not (null es)
          ]
        , [ item $ sourceStep "Check the packages" (Just group) (checkScript pkgs)
          | config.check
          , (group, pkgs) <- packageGroups project.matrix
          ]
        , [ item $ sourceStep "Build the documentation" Nothing "cabal haddock all --disable-documentation --haddock-all --haddock-for-hackage\n"
          | config.haddock
          ]
        ]

    -- The entries in the range of doctest.ghc.
    doctestEntries :: [GhcEntry]
    doctestEntries = case config.doctest of
      Just d -> [e | e <- entries, decide d.ghc e == Included]
      Nothing -> []

    -- The key of the main cache does not depend on the doctest version, so
    -- doctest has its own cache with only the binary.
    doctestSteps :: Doctest -> [Item Node]
    doctestSteps d =
      map
        item
        [ mapping $
            [("name", plain "Find the doctest version"), ("id", plain "doctest")]
              ++ doctestIf []
              ++ [("run", literal findDoctest)]
        , mapping $
            [("uses", plain ("actions/cache/restore@" <> config.actions.cache)), ("id", plain "doctest-cache")]
              ++ doctestIf []
              ++ [
                   ( "with"
                   , mapping
                       [ ("path", plain "~/.local/bin/doctest")
                       , ("key", plain "${{ runner.os }}-${{ steps.versions.outputs.image }}-doctest-${{ steps.doctest.outputs.version }}-ghc-${{ steps.setup.outputs.ghc-version }}")
                       ]
                   )
                 ]
        , mapping $
            [("name", plain "Install doctest")]
              ++ doctestIf [cacheMiss]
              ++ [
                   ( "run"
                   , literal "cabal install doctest --ignore-project --install-method=copy --installdir=\"$HOME/.local/bin\" --overwrite-policy=always --constraint='doctest ==${{ steps.doctest.outputs.version }}'\n"
                   )
                 ]
        , -- A separate save step keeps the binary also if a later step fails.
          mapping $
            [("uses", plain ("actions/cache/save@" <> config.actions.cache))]
              ++ doctestIf [cacheMiss]
              ++ [
                   ( "with"
                   , mapping
                       [ ("path", plain "~/.local/bin/doctest")
                       , ("key", plain "${{ steps.doctest-cache.outputs.cache-primary-key }}")
                       ]
                   )
                 ]
        ]
      where
        cacheMiss :: T.Text
        cacheMiss = "steps.doctest-cache.outputs.cache-hit != 'true'"

        doctestIf :: [T.Text] -> [(T.Text, Node)]
        doctestIf extra = case [condition doctestEntries | doctestEntries /= entries] ++ extra of
          [] -> []
          cs -> [("if", plain (T.intercalate " && " cs))]

        -- A store that already contains doctest gives a plan without it, so the
        -- dry run uses an empty store.
        findDoctest :: T.Text
        findDoctest =
          T.unlines
            [ "version=$(cabal --store-dir=\"$RUNNER_TEMP\"/doctest-store install doctest --ignore-project --dry-run"
                <> maybe "" (\r -> " --constraint=" <> shellQuote ("doctest " <> T.pack (prettyShow r))) d.version
                <> " | sed -n 's/^ - doctest-\\([0-9.]*\\) (exe:doctest).*/\\1/p')"
            , "if [ -z \"$version\" ]; then"
            , "  echo 'The dry run of cabal install shows no doctest version.' >&2"
            , "  exit 1"
            , "fi"
            , "echo \"version=$version\" >> \"$GITHUB_OUTPUT\""
            ]

    doctestScript :: Doctest -> Package -> T.Text
    doctestScript d p =
      T.unlines $
        ["cd " <> shellQuote (T.pack p.directory) | p.directory /= "."]
          ++ [T.unwords ("\"$HOME\"/.local/bin/doctest" : map shellQuote (d.options ++ map T.pack args)) | args <- p.doctestArgs]

    -- cabal check works on the package in the current directory. All lines run
    -- in one shell, so a subshell keeps each cd to its own line.
    checkScript :: [Package] -> T.Text
    checkScript pkgs =
      T.unlines
        [ if p.directory == "." then "cabal check" else "(cd " <> shellQuote (T.pack p.directory) <> " && cabal check)"
        | p <- pkgs
        ]

    -- The content of the tarballs, at the same relative paths as in the project
    -- directory.
    sourceDir :: T.Text
    sourceDir = "\"$RUNNER_TEMP\"/haskell-gha"

    -- The step makes the tarballs of the packages of the matrix entry, so a
    -- package that is not in the project has no tarball. The pattern of a
    -- tarball allows only a version after the name, because the tarball of a
    -- package foo-2d also starts with foo-.
    unpackScript :: [Package] -> T.Text
    unpackScript pkgs =
      T.unlines $
        [ "shopt -s extglob"
        , "cabal sdist all --output-directory=\"$RUNNER_TEMP\"/haskell-gha-sdist"
        , "mkdir " <> sourceDir
        , "for f in cabal.project cabal.project.freeze cabal.project.local; do"
        , "  if [ -f \"$f\" ]; then cp \"$f\" " <> sourceDir <> "; fi"
        , "done"
        ]
          ++ concat
            [ ["mkdir -p " <> dir | p.directory /= "."]
                ++ ["tar -xzf \"$RUNNER_TEMP\"/haskell-gha-sdist/" <> T.pack p.name <> "-+([0-9.]).tar.gz --strip-components=1 -C " <> dir]
            | p <- pkgs
            , let dir = if p.directory == "." then sourceDir else sourceDir <> "/" <> shellQuote (T.pack p.directory)
            ]

    -- A step with a script. The script runs for the given matrix entries, or
    -- for all of them.
    runStep :: T.Text -> Maybe [GhcEntry] -> T.Text -> Node
    runStep = step False

    -- A step that runs in the content of the tarballs, if sdist is true.
    sourceStep :: T.Text -> Maybe [GhcEntry] -> T.Text -> Node
    sourceStep = step config.sdist

    step :: Bool -> T.Text -> Maybe [GhcEntry] -> T.Text -> Node
    step inSource name only script =
      mapping $
        [("name", plain name)]
          ++ [("if", plain (condition es)) | Just es <- [only], es /= entries]
          ++ [sourceWorkingDirectory | inSource]
          ++ [("run", literal script)]

    sourceWorkingDirectory :: (T.Text, Node)
    sourceWorkingDirectory = ("working-directory", plain "${{ runner.temp }}/haskell-gha")

    -- hashFiles only reads files in the workspace, and the content of the
    -- tarballs is outside it. Thus the step gives the hash of the plan to the
    -- cache key as an output.
    planStep :: Node
    planStep =
      mapping $
        [("name", plain "Make the build plan"), ("id", plain "plan")]
          ++ [sourceWorkingDirectory | config.sdist]
          ++ [
               ( "run"
               , literal $
                   T.unlines
                     [ "cabal build all --dry-run"
                     , "echo \"hash=$(sha256sum dist-newstyle/cache/plan.json | cut -d ' ' -f 1)\" >> \"$GITHUB_OUTPUT\""
                     ]
               )
             ]

    condition :: [GhcEntry] -> T.Text
    condition es =
      "contains(fromJSON('[" <> T.intercalate "," ["\"" <> entryText e <> "\"" | e <- es] <> "]'), matrix.ghc)"

    setupStep :: Node
    setupStep =
      mapping
        [ ("uses", plain ("haskell-actions/setup@" <> config.actions.setup))
        , ("id", plain "setup")
        ,
          ( "with"
          , mapping
              [ ("ghc-version", plain "${{ matrix.ghc }}")
              , ("cabal-version", singleQuoted cabalVersion)
              ]
          )
        ]

    cabalVersion :: T.Text
    cabalVersion = case config.cabalVersion of
      CabalLatest -> "latest"
      CabalVersion v -> T.pack (prettyShow v)

    -- An expression cannot read the environment variable ImageOS of the runner,
    -- so the step gives it to the cache key as an output.
    versionsStep :: Node
    versionsStep =
      mapping
        [ ("name", plain "Show the versions")
        , ("id", plain "versions")
        ,
          ( "run"
          , literal $
              T.unlines
                [ "ghc --version"
                , "cabal --version"
                , "echo \"GHC ${{ steps.setup.outputs.ghc-version }}, cabal ${{ steps.setup.outputs.cabal-version }}, image $ImageOS $ImageVersion\" >> \"$GITHUB_STEP_SUMMARY\""
                , "echo \"image=$ImageOS\" >> \"$GITHUB_OUTPUT\""
                ]
          )
        ]

    configureScript :: T.Text
    configureScript =
      heredoc $
        concat
          [ ["jobs: " <> tshow config.jobs]
          , ["tests: True" | config.tests]
          , ["benchmarks: True" | config.benchmarks]
          , ["write-ghc-environment-files: always" | not (null doctestEntries)]
          ]
          ++ concat
            [ "" : stanza p ("ghc-options: " <> config.ghcOptions)
            | not (T.null config.ghcOptions)
            , p <- project.packages
            ]
          ++ case T.lines (T.dropWhileEnd isSpace config.cabalProjectLocal) of
            [] -> []
            ls -> "" : ls

    parallelScript :: [Package] -> T.Text
    parallelScript pkgs =
      heredoc . L.intercalate [""] $ [stanza p ("ghc-options: -j" <> tshow config.jobs) | p <- pkgs]

    stanza :: Package -> T.Text -> [T.Text]
    stanza p line = ["package " <> T.pack p.name, "  " <> line]

    heredoc :: [T.Text] -> T.Text
    heredoc ls = T.unlines $ ["cat >> cabal.project.local <<'EOF'"] ++ ls ++ ["EOF"]

    -- The matrix entries, grouped by their packages.
    packageGroups :: [MatrixEntry] -> [([GhcEntry], [Package])]
    packageGroups es =
      [ ([e.ghc | e <- es, names e.packages == names pkgs], pkgs)
      | pkgs <- L.nubBy (\a b -> names a == names b) (map (.packages) es)
      ]
      where
        names :: [Package] -> [String]
        names = map (.name)

    semaphoreEntries :: [GhcEntry]
    semaphoreEntries = filter hasSemaphore entries

    -- The semaphore needs GHC 9.8. A matrix entry is an exact version or a
    -- major series, so the range decides each entry completely.
    hasSemaphore :: GhcEntry -> Bool
    hasSemaphore e = decide (orLaterVersion (mkVersion [9, 8])) e == Included

    testEntries :: [GhcEntry]
    testEntries = [e.ghc | e <- project.matrix, any (.hasTestSuite) e.packages]

    cacheRestore :: Node
    cacheRestore =
      mapping
        [ ("uses", plain ("actions/cache/restore@" <> config.actions.cache))
        , ("id", plain "cache")
        ,
          ( "with"
          , mapping
              [ ("path", plain "${{ steps.setup.outputs.cabal-store }}")
              , ("key", plain $ cachePrefix <> "${{ steps.plan.outputs.hash }}")
              , ("restore-keys", plain cachePrefix)
              ]
          )
        ]

    -- A store from another image can link against system libraries that this
    -- image does not have.
    cachePrefix :: T.Text
    cachePrefix = "${{ runner.os }}-${{ steps.versions.outputs.image }}-ghc-${{ steps.setup.outputs.ghc-version }}-"

    cacheSave :: Node
    cacheSave =
      mapping
        [ ("uses", plain ("actions/cache/save@" <> config.actions.cache))
        , ("if", plain "steps.cache.outputs.cache-hit != 'true'")
        ,
          ( "with"
          , mapping
              [ ("path", plain "${{ steps.setup.outputs.cabal-store }}")
              , ("key", plain "${{ steps.cache.outputs.cache-primary-key }}")
              ]
          )
        ]

    aptScript :: [T.Text] -> T.Text
    aptScript packages =
      T.unlines
        [ "sudo apt-get update"
        , "sudo apt-get install -y --no-install-recommends " <> T.unwords (map shellQuote packages)
        ]

    tshow :: Int -> T.Text
    tshow = T.pack . show
